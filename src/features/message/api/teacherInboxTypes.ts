import type {
  ComplaintStatus,
  MessageSenderRole,
  RiskLevel,
  TeacherAllowedAction,
  UserRole,
  WaitingFor,
} from '../../../shared/types';

// Shapes in this file follow the backend teacher complaint DTOs (complaint/query/dto, complaint/teacher/dto/query).
// Do not add fields the backend does not define. Dates are LocalDateTime strings without a zone (server time, KST).
// GET /teacher/complaints/{id}/risk and /history reuse TeacherRiskResponse and TeacherHistoryResponse
// from escalationTypes, the same DTOs the admin escalation screens read.

export type ComplaintListSort = 'LATEST' | 'OLDEST';

// GET /teacher/complaints query. The page size is fixed at 10 by the server.
export type ComplaintListQuery = {
  // 0-based.
  page?: number;
  // Title, student name, counterpart name, and message content; up to 100 characters.
  keyword?: string;
  // DRAFT complaints are never listed for teachers.
  status?: ComplaintStatus;
  // Filters by the latest teacher review when there is one, else by the latest completed analysis.
  riskLevel?: RiskLevel;
  sort?: ComplaintListSort;
};

export const COMPLAINT_PAGE_SIZE = 10;

export type ComplaintListItem = {
  complaintId: number;
  title: string;
  studentId: number;
  studentName: string;
  // The parent's name in the teacher list.
  counterpartName: string | null;
  counterpartRole: UserRole;
  academicYear: number | null;
  grade: number | null;
  classNo: number | null;
  status: ComplaintStatus;
  waitingFor: WaitingFor;
  riskAnalysisId: number | null;
  riskLevel: RiskLevel | null;
  // Generated by the server's summary provider, which is still a mock.
  aiSummary: string | null;
  latestReceivedAt: string | null;
};

export type ComplaintPageResponse = {
  content: ComplaintListItem[];
  page: number;
  size: number;
  totalElements: number;
  totalPages: number;
  first: boolean;
  last: boolean;
  hasNext: boolean;
  hasPrevious: boolean;
};

// GET /teacher/complaints/{complaintId}
export type TeacherComplaintDetailResponse = {
  complaintId: number;
  title: string;
  studentName: string;
  parentName: string;
  academicYear: number | null;
  grade: number | null;
  classNo: number | null;
  status: ComplaintStatus;
  waitingFor: WaitingFor;
  submittedAt: string;
  riskLevel: RiskLevel | null;
};

export type TeacherConversationMessage = {
  // "message:{id}"
  messageId: string;
  senderRole: Extract<MessageSenderRole, 'PARENT' | 'TEACHER'>;
  senderName: string;
  // A parent message whose latest analysis is above LOW comes as a buffered summary instead of the original.
  content: string;
  sentAt: string;
  summarized: boolean;
};

// GET /teacher/complaints/{complaintId}/messages
export type TeacherConversationResponse = {
  complaintId: number;
  // EMERGENCY actions while the safety lock holds.
  allowedActions: TeacherAllowedAction[];
  messages: TeacherConversationMessage[];
};

// POST /teacher/complaints/{complaintId}/messages/{messageId}/original-views. One sent message's original;
// every call records an ORIGINAL_VIEWED event.
export type TeacherOriginalViewResponse = {
  complaintId: number;
  messageId: number;
  content: string;
  viewedAt: string;
};

// POST /teacher/complaints/{complaintId}/close answers { message } instead of a DTO. Only an OPEN complaint
// waiting for the parent closes (else 409 RESPONSE_NOT_EDITABLE with the reason); answering does not close it on its own.
export type TeacherCloseResponse = {
  message: string;
};

// GET /teacher/complaints/{complaintId}/response-templates. Latest active version of each High template.
// An empty list when the complaint has no completed analysis; 409 RESPONSE_NOT_EDITABLE when the effective
// level is not HIGH, the complaint is not waiting for the teacher, or the safety lock holds.
// contentTemplate holds {{variable}} slots, listed in requiredVariables.
export type ResponseTemplateResponse = {
  templateId: number;
  versionId: number;
  code: string;
  name: string;
  version: number;
  contentTemplate: string;
  requiredVariables: string[];
};

// POST .../response-templates/{versionId}/adoptions (201). Every required variable needs a non-blank value;
// finalContent @NotBlank @Size(max = 1500) is the reply the teacher confirmed.
export type ResponseTemplateAdoptionRequest = {
  variables: Record<string, string>;
  finalContent: string;
};

export type ResponseTemplateAdoptionResponse = {
  adoptionId: number;
  complaintId: number;
  templateVersionId: number;
  renderedContent: string;
  finalContent: string;
  adoptedAt: string;
};

// Teacher reply DTOs (complaint/teacher/dto/reply). The server keeps one draft per complaint and teacher,
// and accepts a reply only while the complaint is OPEN and waiting for the teacher (else 409 RESPONSE_NOT_EDITABLE).

// Body of PUT /response-draft and POST /responses. @NotBlank, @Size(max = 1500).
export type TeacherResponseRequest = {
  content: string;
};

export const TEACHER_RESPONSE_MAX_LENGTH = 1500;

// POST /teacher/complaints/{complaintId}/response/ai-draft. Not stored as a draft; the server records
// an AI_DRAFT_GENERATED event. The generator is still a mock.
export type TeacherAiDraftResponse = {
  complaintId: number;
  content: string;
  modelName: string;
  generatedAt: string;
};

// GET and PUT /teacher/complaints/{complaintId}/response-draft. GET answers 404 RESPONSE_DRAFT_NOT_FOUND
// when nothing was saved.
export type TeacherResponseDraftResponse = {
  responseDraftId: number;
  complaintId: number;
  content: string;
  createdAt: string;
  updatedAt: string;
};

// POST /teacher/complaints/{complaintId}/responses. Sends the reply (the saved draft becomes it) and
// hands the turn to the parent (waitingFor PARENT).
export type TeacherResponseSubmissionResponse = {
  responseId: number;
  complaintId: number;
  content: string;
  complaintStatus: ComplaintStatus;
  waitingFor: WaitingFor;
  sentAt: string;
};
